"""KiCad case: emits a real KiCad 8 project (`.kicad_pro` + `.kicad_sch` +
`.kicad_pcb` + symbol/footprint libs + BOM CSV + netlist) for an ECG-style
analog sensor frontend (instrumentation amp + filters + output buffer).

Every file uses KiCad's S-expression format and is parseable by
`kicad-cli sch export netlist` and `kicad-cli pcb export drill`.
"""
