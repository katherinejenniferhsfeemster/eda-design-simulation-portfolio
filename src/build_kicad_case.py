PROJECT_NAME = "sensor_frontend"


def uu() -> str:
    return str(uuid.uuid4())


def kicad_pro() -> str:
    return json.dumps({
        "board": {"3dviewports": [], "design_settings": {"defaults": {}}},
        "boards": [],
        "cvpcb": {"equivalence_files": []},
        "libraries": {"pinned_footprint_libs": [], "pinned_symbol_libs": []},
        "meta": {"filename": f"{PROJECT_NAME}.kicad_pro", "version": 1},
        "net_settings": {"classes": [{"name": "Default", "clearance": 0.2,
                                      "track_width": 0.25, "via_diameter": 0.6,
                                      "via_drill": 0.3}]},
        "pcbnew": {"last_paths": {"netlist": f"{PROJECT_NAME}.net"}},
        "schematic": {"annotate_start_num": 0, "legacy_lib_list": []},
        "sheets": [[uu(), "Root"]],
        "text_variables": {
            "TITLE": "Sensor Frontend (ECG AFE)",
            "REV": "R1",
            "COMPANY": "Katherine Feemster · EDA",
        },
    }, indent=2)


